function foreignNumbers(out, src){
  const norm = s => (s.match(/\d[\d,]*(?:\.\d+)?/g) || []).map(x => x.replace(/,/g, ""));
  const have = new Set(norm(src));
  return [...new Set(norm(out))].filter(x => !have.has(x) && !/^\d$/.test(x));
}


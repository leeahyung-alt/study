function growthText(cur, prev){
  if(prev.won === 0) return null;
  if(prev.won < 0 && cur.won >= 0) return {txt:"흑자 전환", val:null};
  if(prev.won < 0 && cur.won < 0) return {txt:(cur.won < prev.won ? "적자 확대" : "적자 축소"), val:null};
  if(prev.won > 0 && cur.won < 0) return {txt:"적자 전환", val:null};
  const g = (cur.won - prev.won) / prev.won * 100;
  return {txt:pct(g), val:g};
}

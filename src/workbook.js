function parseNum(raw){
  if(raw === undefined || raw === null) return null;
  let s = String(raw).trim();
  if(!s) return null;
  let neg = false;
  if(/^\(.*\)$/.test(s)){ neg = true; s = s.slice(1, -1); }
  if(/^[△▲]/.test(s)){ neg = true; s = s.slice(1); }
  s = s.replace(/[,\s]/g, "");
  if(s.startsWith("-")){ neg = !neg; s = s.slice(1); }
  if(!/^\d+(\.\d+)?$/.test(s)) return NaN;
  const n = parseFloat(s);
  return neg ? -n : n;
}
function fmtWon(won){
  const a = Math.abs(won), sign = won < 0 ? "-" : "";
  if(a >= 1e12) return sign + (a / 1e12).toLocaleString("ko-KR", {maximumFractionDigits:2}) + "조원";
  if(a >= 1e8) return sign + (a / 1e8).toLocaleString("ko-KR", {maximumFractionDigits:1}) + "억원";
  if(a >= 1e4) return sign + (a / 1e4).toLocaleString("ko-KR", {maximumFractionDigits:1}) + "만원";
  return sign + a.toLocaleString("ko-KR") + "원";
}

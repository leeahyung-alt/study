function runCalc(c, id){
  const C = CALCS[id]; const v = {}; const missing = []; const noUnit = [];
  for(const k of C.need){ const x = numVal(c, k); if(!x) missing.push(NUMLABEL[k] || k); else if(x.won === null) noUnit.push(NUMLABEL[k] || k); else v[k] = x; }
  if(missing.length) return {id, name:C.name, formula:C.formula, missing};
  if(noUnit.length) return {id, name:C.name, formula:C.formula, missing:noUnit.map(s => s + "(단위)")};
  v._op_prev = numVal(c, "op_prev"); v._rev_prev = numVal(c, "rev_prev");
  if(v._op_prev && v._op_prev.won === null) v._op_prev = null;
  if(v._rev_prev && v._rev_prev.won === null) v._rev_prev = null;
  const r = C.run(v);
  if(!r) return {id, name:C.name, formula:C.formula, missing:[], invalid:true};
  return Object.assign({id, name:C.name, formula:C.formula}, r);
}

